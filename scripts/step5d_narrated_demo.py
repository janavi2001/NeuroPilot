#!/usr/bin/env python3
"""Narrated end-to-end demo: the Step 5c video, re-paced to an ElevenLabs voiceover.

The narration (scripts/step5d_narration.yaml, generated by step5d_voiceover.py)
drives the timing: every beat lasts at least as long as its line, captions
light up word by word from ElevenLabs' character timestamps, and the panel being
talked about is spotlighted while the rest is dimmed. Data are the same as in
Step 5c: recorded BETA trials re-decoded and checked against the logged
decisions, the real GR00T/LIBERO runs and their Cosmos re-renders, and numbers
read from the stored results. Slowed playback is labelled on screen.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field, replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cosmos.controls import read_frames  # noqa: E402
from interface.visualization.hero_renderer import ACCENT, MUTED  # noqa: E402
from interface.visualization.mission_renderer import COLORS, MissionRenderer, MissionState  # noqa: E402

_spec = importlib.util.spec_from_file_location("step5c", Path(__file__).with_name("step5c_mission_demo.py"))
step5c = importlib.util.module_from_spec(_spec)
sys.modules["step5c"] = step5c
_spec.loader.exec_module(step5c)

FPS = step5c.FPS
SOURCE_FPS = step5c.SOURCE_FPS
VOICE_DIR = Path("artifacts/step5_voice")
SCRIPT = Path("scripts/step5d_narration.yaml")
SAMPLE_RATE = 44100
TAIL = 0.55  # silence after each line before the next beat
NVIDIA = "#76b900"
KEYWORDS = {"bowl": COLORS["BOWL"], "plate": COLORS["PLATE"], "cheese": COLORS["CHEESE"], "wine": COLORS["WINE"],
            "stove": COLORS["STOVE"], "neuropilot": ACCENT, "gr00t": NVIDIA, "cosmos": NVIDIA, "nvidia": NVIDIA,
            "nvidia's": NVIDIA, "neuralink": "#d2a8ff", "neuralink's": "#d2a8ff", "unsure": MUTED, "twice": ACCENT,
            "agree": ACCENT, "brain": "#d2a8ff", "rhythm": "#d2a8ff", "outlines": ACCENT, "repaints": ACCENT,
            "worlds": ACCENT, "what": ACCENT, "complete": ACCENT}
# Word-triggered spotlights for the explained command and the Cosmos explainer: (first word, panels).
CUES = {
    "s04_eeg": [("Here's", ("stimulus",)), ("Their", ("eeg",))],
    "s05_decoder": [("Our", ("race",))],
    "s06_confirm": [("To", ("history", "pipeline"))],
    "s07_instruction": [("That", ("banner", "pipeline"))],
    "s08_groot": [("NVIDIA's", ("robot",))],
    "s09_check": [("The", ("banner", "pipeline"))],
    "s10_cosmos": [("But", ("x1",)), ("Cosmos", ("x2",)), ("repaints", ("x3",))],
    "s03_idea": [("My", ("i1",)), ("say", ("i1", "i2")), ("capable", ("i3",))],
}


@dataclass
class Line:
    id: str
    words: list[str]  # caption words
    starts: list[float]  # seconds from the start of the line
    duration: float
    audio: np.ndarray  # mono float32 at SAMPLE_RATE


@dataclass
class Beat:
    frames: list[MissionState]
    line: Line | None = None
    anchor: int = 0  # frame where the line starts
    stage_focus: bool = False  # spotlight follows the command stage instead of word cues
    extras: list = field(default_factory=list)


def word_starts(alignment: dict) -> list[float]:
    """Start time of each space-separated word from ElevenLabs character timings."""
    chars, starts = alignment["characters"], alignment["character_start_times_seconds"]
    out, new_word = [], True
    for char, start in zip(chars, starts):
        if char.isspace():
            new_word = True
        elif new_word:
            out.append(float(start))
            new_word = False
    return out


def load_lines() -> dict[str, Line]:
    import yaml

    lines = {}
    for segment in yaml.safe_load(SCRIPT.read_text())["segments"]:
        meta = json.loads((VOICE_DIR / f"{segment['id']}.json").read_text())
        if meta["spoken"] != segment.get("speak", segment["text"]):
            raise RuntimeError(f"{segment['id']}: voiceover is stale, run scripts/step5d_voiceover.py")
        words = segment["text"].split()
        starts = word_starts(meta["alignment"])
        if len(starts) != len(words):
            raise RuntimeError(f"{segment['id']}: {len(words)} caption words but {len(starts)} spoken words")
        raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(VOICE_DIR / f"{segment['id']}.mp3"), "-f", "f32le",
                              "-ac", "1", "-ar", str(SAMPLE_RATE), "-"], capture_output=True, check=True).stdout
        audio = np.frombuffer(raw, np.float32)
        lines[segment["id"]] = Line(segment["id"], words, starts, len(audio) / SAMPLE_RATE, audio)
    return lines


def fit(beat: Beat) -> Beat:
    """Hold the last frame until the line (plus a short tail) has finished."""
    if beat.line is not None:
        need = beat.anchor + int(np.ceil((beat.line.duration + TAIL) * FPS))
        beat.frames += [beat.frames[-1]] * max(0, need - len(beat.frames))
    return beat


def frames_for(line: Line, extra: float = TAIL) -> int:
    return int(np.ceil((line.duration + extra) * FPS))


def caption_at(line: Line, t: float) -> list[tuple[str, str | None, bool]]:
    return [(word, KEYWORDS.get(word.strip(".,:;?!“”\"").lower()), start <= t)
            for word, start in zip(line.words, line.starts)]


def cue_focus(line: Line, t: float) -> tuple[str, ...]:
    focus: tuple[str, ...] = ()
    for word, panels in CUES.get(line.id, []):
        index = line.words.index(word)
        if line.starts[index] <= t + 0.05:
            focus = panels
    return focus


def stage_focus(state: MissionState) -> tuple[str, ...]:
    if state.stage >= 5:
        return ("banner", "pipeline")
    if state.stage == 3:
        return ("robot",)
    if state.stage == 2 and not state.live:
        return ("banner", "pipeline")
    return ("race", "history") if state.look is not None else ()


# ------------------------------------------------------------------ beats
def ms(fields: dict, **overrides) -> MissionState:
    """MissionState from a base dict; explicit keyword values win over the base.

    The history list is copied: beats are built ahead of rendering, so a shared list
    would show later commands' looks in earlier frames.
    """
    merged = {**fields, **overrides}
    merged["history"] = list(merged.get("history", []))
    return MissionState(**merged)


def card_beat(line: Line, card) -> Beat:
    return fit(Beat([MissionState(scene="card", card=card) for _ in range(frames_for(line))], line))


def idea_beat(line: Line) -> Beat:
    return fit(Beat([MissionState(scene="idea") for _ in range(frames_for(line))], line))


def first_command_beats(lines, decision, looks, clip, base, history) -> list[Beat]:
    """Command 1, explained step by step in the plain simulator (looks slowed down and labelled)."""
    sim = clip["sim"]
    common = dict(base, command=1, intended=decision["intended"], history=history, robot_frame=sim[0],
                  robot_caption="the actual run · LIBERO simulator", stimulus=True)
    (look1, track1), (look2, track2) = looks
    beats = []

    n = frames_for(lines["s04_eeg"])
    play = max(1, n - int(0.8 * FPS))
    speed = track1.decision_seconds / (play / FPS)
    beats.append(Beat([ms(common, look=track1, look_elapsed=track1.decision_seconds * min(1, (i + 1) / play),
                                    live=i < play, stage=0, speed_note=f"replayed at {speed:.2f}× speed",
                                    banner="the person looks at BOWL  ·  look 1", banner_color=MUTED)
                       for i in range(n)], lines["s04_eeg"]))
    history.append(f"#1 saw BOWL   → {look1['intent']:<6} @{look1['decision_seconds']:.1f}s  {look1['event']}")
    preview = dict(common, look=track1, look_elapsed=track1.decision_seconds, candidate=look1["intent"], stage=1)
    beats.append(Beat([ms(preview, banner=f"decoded {look1['intent']}  →  PREVIEW · look again to confirm",
                                    banner_color=COLORS[look1["intent"]])
                       for _ in range(frames_for(lines["s05_decoder"]))], lines["s05_decoder"]))

    n = frames_for(lines["s06_confirm"])
    play = int(0.6 * n)
    speed = track2.decision_seconds / (play / FPS)
    frames = [ms(preview, look=track2, look_elapsed=track2.decision_seconds * (i + 1) / play,
                 live=True, speed_note=f"replayed at {speed:.2f}× speed",
                           banner="the person looks at BOWL again  ·  look 2", banner_color=MUTED) for i in range(play)]
    confirmed = dict(preview, look=track2, look_elapsed=track2.decision_seconds, candidate=None,
                     confirmed=decision["confirmed"])
    frames += [ms(confirmed, stage=2, banner=f"decoded {look2['intent']} again  →  CONFIRMED",
                            banner_color=ACCENT) for _ in range(n - play)]
    beats.append(Beat(frames, lines["s06_confirm"]))
    history.append(f"#1 saw BOWL   → {look2['intent']:<6} @{look2['decision_seconds']:.1f}s  {look2['event']}")

    settled = dict(confirmed, instruction=clip["instruction"])
    beats.append(Beat([ms(settled, stage=2, banner=f"SELECT BOWL  →  “{clip['instruction']}”",
                                    banner_color=COLORS["BOWL"]) for _ in range(frames_for(lines["s07_instruction"]))],
                      lines["s07_instruction"]))

    n = frames_for(lines["s08_groot"])
    slow = max(0.35, len(sim) / SOURCE_FPS / (n / FPS - 0.5))
    beats.append(Beat([ms(settled, robot_frame=sim[min(len(sim) - 1, int(i / FPS * SOURCE_FPS * slow))],
                          robot_caption=f"the actual run · LIBERO simulator · slowed to {slow:.2f}×",
                          stage=3, banner="GR00T is acting on the instruction")
                       for i in range(n)], lines["s08_groot"]))
    history.append(f"#1 GR00T: {clip['instruction'][:34]} {'✓' if clip['success'] else '✗'}")
    beats.append(Beat([ms({**settled, "robot_frame": sim[-1]}, stage=5,
                                    banner="✓ task complete  ·  LIBERO's own success check", banner_color=ACCENT)
                       for _ in range(frames_for(lines["s09_check"]))], lines["s09_check"]))
    return [fit(b) for b in beats]


def explain_beat(line: Line, explain) -> Beat:
    sim, edges, cosmos = explain
    length = min(len(sim), len(edges), len(cosmos))
    frames = []
    for i in range(frames_for(line)):
        k = min(length - 1, int(i * SOURCE_FPS * 0.6 / FPS) % (length + 10))  # 0.6x, short hold between loops
        frames.append(MissionState(scene="explain", explain_frames=[sim[k], edges[k], cosmos[k]]))
    return fit(Beat(frames, line))


def command_beat(line: Line, number, decision, looks, clip, base, history, anchor_on: str) -> Beat:
    frames = [replace(s, history=list(s.history))  # snapshot as each frame is produced
              for s in step5c.command_scenes(number, decision, looks, clip, base, history)]
    if anchor_on == "start":
        anchor = 0
    elif anchor_on == "second_look":
        second = looks[1][1]
        anchor = next(i for i, s in enumerate(frames) if s.look is second and s.live)
    else:  # robot
        anchor = next(i for i, s in enumerate(frames) if s.stage == 3)
    return fit(Beat(frames, line, anchor=anchor, stage_focus=True))


def worlds_beat(line: Line, worlds, numbers) -> Beat:
    hero = worlds["frames"]
    length = min(len(f) for f in hero.values())
    n = frames_for(line)
    slow = (length / SOURCE_FPS) / max(1e-3, n / FPS - 0.8)
    lines = ["Same robot motion in every world.", "edge agreement with the real run, mean of",
             f"all {numbers['cosmos_clips']} Cosmos clips: F1 {numbers['edge_f1']}",
             f"(original simulator: {numbers['edge_f1_sim']})", "success label: from the simulator run"]
    frames = [MissionState(scene="worlds", world_frames={w: hero[w][min(length - 1, int(i / FPS * SOURCE_FPS * slow))]
                                                         for w in step5c.WORLD_ORDER},
                           world_titles=step5c.WORLD_TITLES,
                           sim_frame=worlds["sim"][min(length - 1, int(i / FPS * SOURCE_FPS * slow))], history=lines)
              for i in range(n)]
    return fit(Beat(frames, line))


def build(lines, decisions, tracks, clips, explain, worlds, numbers, subject) -> list[Beat]:
    stats = {"6-target accuracy, 10 held-out subjects": numbers["accuracy"],
             "wrong actions with two-look confirm": f"{numbers['confirm_wrong']} ({numbers['confirm_detail']})",
             "information rate, early stopping": numbers["bits"],
             "GR00T alone, 5 tasks × 10 episodes": numbers["baseline"]}
    base = dict(scene="kitchen", commands_total=len(decisions), stats=stats)
    history: list[str] = []
    beats = [card_beat(lines["s01_title"], ("NEUROPILOT", "Brain signals choose.  A robot acts.",
                                             ["· real recorded EEG  ·  NVIDIA GR00T  ·  NVIDIA Cosmos ·"])),
             card_beat(lines["s02_spark"], ("THE SPARK", "the Neuralink Student Symposium",
                                             ["What would it take for a brain signal",
                                              "to help someone act in the physical world?"])),
             idea_beat(lines["s03_idea"])]
    beats += first_command_beats(lines, decisions[0], tracks[0], clips[decisions[0]["label"]], base, history)
    beats.append(explain_beat(lines["s10_cosmos"], explain))
    plan = [("s11_plate", "start"), ("s12_unsure", "second_look"), ("s13_wine", "robot"), ("s14_stove", "robot")]
    for number, ((line_id, anchor), decision, looks) in enumerate(zip(plan, decisions[1:], tracks[1:]), start=2):
        beats.append(command_beat(lines[line_id], number, decision, looks, clips[decision["label"]], base, history,
                                  anchor))
    beats.append(worlds_beat(lines["s15_worlds"], worlds, numbers))
    end = ("NEUROPILOT", "brain signals choose  →  a robot acts",
           [f"Brain → robot: {numbers['bci_correct']} commands chose the intended task, "
            f"{numbers['bci_success']} completed by GR00T",
            f"SSVEP decoder, 6 targets, 10 held-out subjects: {numbers['accuracy']} accuracy  ·  "
            f"{numbers['confirm_wrong']} wrong actions with two-look confirm  ·  {numbers['bits']}",
            f"GR00T N1.7 alone: {numbers['baseline']} kitchen episodes  ·  Cosmos 3: {numbers['cosmos_clips']} "
            f"photoreal clips, edge F1 {numbers['edge_f1']} vs the real run",
            f"· recorded public EEG (subject S{subject}, never used for tuning), replayed offline, not a live participant ·",
            "· success is LIBERO's check in simulation; Cosmos re-renders those runs, GR00T was not re-tested in them ·"])
    beats.append(card_beat(lines["s16_end"], end))
    return beats


def decorate(beats: list[Beat]):
    """Yield final frames with clock, captions and spotlight; return audio placements via the list it fills."""
    placements = []
    clock = 0
    for beat in beats:
        if beat.line is not None:
            placements.append((clock + beat.anchor, beat.line))
        for i, state in enumerate(beat.frames):
            extra = {"clock": (clock + i) / FPS}
            if beat.line is not None:
                t = (i - beat.anchor) / FPS
                if 0 <= t <= beat.line.duration + TAIL:
                    extra["caption"] = caption_at(beat.line, t)
                    if not beat.stage_focus:
                        extra["focus"] = cue_focus(beat.line, t)
            if beat.stage_focus:
                extra["focus"] = stage_focus(state)
            yield replace(state, **extra), placements
        clock += len(beat.frames)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=Path("artifacts/videos/step5/neuropilot_narrated.mp4"))
    parser.add_argument("--max-frames", type=int, default=0, help="stop early (preview)")
    args = parser.parse_args()

    lines = load_lines()
    jobs = json.loads((step5c.GR00T / "bci_jobs.json").read_text())
    decisions = jobs["decisions"]
    for decision, job in zip(decisions, jobs["jobs"]):
        decision["label"] = job["label"]
    numbers = step5c.load_numbers()
    config, tracks = step5c.build_tracks(decisions, jobs["subject"])
    clips = {}
    for decision in decisions:
        label = decision["label"]
        result = json.loads((step5c.GR00T / "remote_results" / label / "result.json").read_text())
        sim, _ = read_frames(step5c.COSMOS / "inputs" / label / "rgb.mp4")
        clips[label] = {"sim": sim, "instruction": result["instruction"], "success": result["successes"][0]}
        world = step5c.COMMAND_WORLDS.get(label)
        if world:
            clips[label].update(world=world, cosmos=read_frames(step5c.cosmos_clip(label, world))[0])
    first = decisions[0]["label"]
    explain = (clips[first]["sim"], read_frames(step5c.COSMOS / "inputs" / first / "control_edge.mp4")[0],
               read_frames(step5c.cosmos_clip(first, "modern_kitchen"))[0])
    worlds = {"frames": {w: read_frames(step5c.cosmos_clip("bci_02_PLATE", w))[0] for w in step5c.WORLD_ORDER},
              "sim": clips["bci_02_PLATE"]["sim"]}
    beats = build(lines, decisions, tracks, clips, explain, worlds, numbers, jobs["subject"])

    renderer = MissionRenderer(config.targets, list(config.channels), config.margin_threshold)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        silent, voice = Path(tmp) / "video.mp4", Path(tmp) / "voice.wav"
        encoder = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s",
                                    "1920x1080", "-r", str(FPS), "-i", "-", "-c:v", "libx264", "-crf", "18",
                                    "-preset", "medium", "-pix_fmt", "yuv420p", str(silent)], stdin=subprocess.PIPE)
        count, placements = 0, []
        for state, placements in decorate(beats):
            encoder.stdin.write(renderer.frame(state).tobytes())
            count += 1
            if count % 250 == 0:
                print(f"{count} frames ({count / FPS:.0f} s)", flush=True)
            if args.max_frames and count >= args.max_frames:
                break
        encoder.stdin.close()
        if encoder.wait() != 0:
            raise RuntimeError("ffmpeg video encode failed")
        renderer.close()

        track = np.zeros(int(count / FPS * SAMPLE_RATE) + SAMPLE_RATE, np.float32)
        for frame, line in placements:
            start = int(frame / FPS * SAMPLE_RATE)
            if start >= len(track):
                continue
            end = min(len(track), start + len(line.audio))
            track[start:end] += line.audio[:end - start]
        peak = np.abs(track).max() or 1.0
        pcm = (np.clip(track / max(peak, 1.0), -1, 1) * 32767).astype("<i2")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "s16le", "-ar", str(SAMPLE_RATE), "-ac", "1", "-i", "-",
                        str(voice)], input=pcm.tobytes(), check=True)
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(silent), "-i", str(voice), "-map", "0:v", "-map", "1:a",
                        "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-af", "loudnorm=I=-16:TP=-1.5:LRA=11",
                        "-shortest", "-movflags", "+faststart", str(args.output)], check=True)
    print(f"wrote {args.output}: {count} frames, {count / FPS:.1f} s, {len(placements)} narration lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
